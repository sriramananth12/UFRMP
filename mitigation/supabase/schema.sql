-- Mitigation portal: tables, logins and access rules for Supabase.
-- Run in the Supabase dashboard: SQL Editor > New query > paste all of this > Run.
-- Safe to re-run. Nothing here touches the UFRMP dashboard's tables in "public".
--
-- Each programme gets its own schema (landslide, drought, ...) holding the same
-- tables the UFRMP dashboard uses, so programme data never mixes. Inside a
-- schema, a master login sees and edits every state; a state login sees and
-- edits only its own state. Postgres row-level security enforces this, so it
-- holds even for someone calling Supabase directly with the public anon key.
-- After running this, add the schemas under Exposed schemas (see SETUP.md).

create or replace function public.mitigation_setup_schema(s text) returns void
language plpgsql as $setup$
begin
  execute format('create schema if not exists %I', s);
  execute format('grant usage on schema %I to anon, authenticated, service_role', s);

  -- One row per work item; the full work object is kept in `data`.
  execute format($q$
    create table if not exists %1$I.works (
      id          text primary key,
      data        jsonb not null default '{}'::jsonb,
      seq         bigint generated by default as identity,
      updated_at  timestamptz not null default now(),
      city_id     text
    )$q$, s);
  execute format('create index if not exists works_city_id_idx on %I.works (city_id)', s);

  -- One row per Implementation Gantt line, grouped by state.
  execute format($q$
    create table if not exists %1$I.gantt_data (
      id          text primary key,
      city_id     text not null,
      data        jsonb not null default '{}'::jsonb,
      seq         bigint generated by default as identity,
      updated_at  timestamptz not null default now()
    )$q$, s);
  execute format('create index if not exists gantt_data_city_id_idx on %I.gantt_data (city_id)', s);

  -- One row per Budget Matrix line item, grouped by state.
  execute format($q$
    create table if not exists %1$I.budget_matrix (
      id          text primary key,
      city_id     text not null,
      data        jsonb not null default '{}'::jsonb,
      seq         bigint generated by default as identity,
      updated_at  timestamptz not null default now()
    )$q$, s);
  execute format('create index if not exists budget_matrix_city_id_idx on %I.budget_matrix (city_id)', s);

  -- Everything else as one JSON string per key, one key per state
  -- ("components@<stateId>", "photos:<workId>", ...) with that state in city_id.
  execute format($q$
    create table if not exists %1$I.kv_store (
      key         text primary key,
      value       text not null,
      updated_at  timestamptz not null default now(),
      city_id     text
    )$q$, s);
  execute format('create index if not exists kv_store_city_id_idx on %I.kv_store (city_id)', s);

  -- Logins: one profile per Supabase Auth user that may use this programme.
  -- role 'city' is a state login (the page calls the unit a state).
  execute format($q$
    create table if not exists %1$I.user_profiles (
      user_id     uuid primary key references auth.users (id) on delete cascade,
      username    text not null,
      role        text not null check (role in ('master', 'city')),
      city_id     text,
      created_at  timestamptz not null default now(),
      constraint user_profiles_role_city check ((role = 'master' and city_id is null) or (role = 'city' and city_id is not null))
    )$q$, s);
  execute format('create unique index if not exists user_profiles_username_key on %I.user_profiles (lower(username))', s);

  -- Readable copies of passwords set from the User Logins page, for the master.
  execute format($q$
    create table if not exists %1$I.login_passwords (
      user_id     uuid primary key references auth.users (id) on delete cascade,
      password    text not null,
      updated_at  timestamptz not null default now()
    )$q$, s);

  execute format($q$
    create or replace function %1$I.is_master() returns boolean
    language sql stable security definer set search_path = %1$I as $f$
      select exists (select 1 from %1$I.user_profiles where user_id = auth.uid() and role = 'master');
    $f$$q$, s);
  execute format($q$
    create or replace function %1$I.user_city() returns text
    language sql stable security definer set search_path = %1$I as $f$
      select city_id from %1$I.user_profiles where user_id = auth.uid() and role = 'city';
    $f$$q$, s);
  execute format('revoke all on function %1$I.is_master() from public, anon', s);
  execute format('revoke all on function %1$I.user_city() from public, anon', s);
  execute format('grant execute on function %1$I.is_master() to authenticated', s);
  execute format('grant execute on function %1$I.user_city() to authenticated', s);

  -- Profiles: read your own, or all as master. They change only through the
  -- mitigation-admin Edge Function (service role).
  execute format('alter table %I.user_profiles enable row level security', s);
  execute format('drop policy if exists "read own or all as master" on %I.user_profiles', s);
  execute format('create policy "read own or all as master" on %1$I.user_profiles for select to authenticated '
                 'using (user_id = auth.uid() or (select %1$I.is_master()))', s);
  execute format('revoke all on %I.user_profiles from anon, authenticated', s);
  execute format('grant select on %I.user_profiles to authenticated', s);

  execute format('alter table %I.login_passwords enable row level security', s);
  execute format('drop policy if exists "master reads" on %I.login_passwords', s);
  execute format('create policy "master reads" on %1$I.login_passwords for select to authenticated '
                 'using ((select %1$I.is_master()))', s);
  execute format('revoke all on %I.login_passwords from anon, authenticated', s);
  execute format('grant select on %I.login_passwords to authenticated', s);

  -- Data tables: the master can do anything, a state login only touches rows
  -- whose city_id is its own state. The anon key alone gets nothing.
  execute format('alter table %I.works enable row level security', s);
  execute format('alter table %I.gantt_data enable row level security', s);
  execute format('alter table %I.budget_matrix enable row level security', s);
  execute format('alter table %I.kv_store enable row level security', s);
  execute format('drop policy if exists "master or own state" on %I.works', s);
  execute format('drop policy if exists "master or own state" on %I.gantt_data', s);
  execute format('drop policy if exists "master or own state" on %I.budget_matrix', s);
  execute format('drop policy if exists "master or own state" on %I.kv_store', s);
  execute format('create policy "master or own state" on %1$I.works for all to authenticated '
                 'using ((select %1$I.is_master()) or city_id = (select %1$I.user_city())) '
                 'with check ((select %1$I.is_master()) or city_id = (select %1$I.user_city()))', s);
  execute format('create policy "master or own state" on %1$I.gantt_data for all to authenticated '
                 'using ((select %1$I.is_master()) or city_id = (select %1$I.user_city())) '
                 'with check ((select %1$I.is_master()) or city_id = (select %1$I.user_city()))', s);
  execute format('create policy "master or own state" on %1$I.budget_matrix for all to authenticated '
                 'using ((select %1$I.is_master()) or city_id = (select %1$I.user_city())) '
                 'with check ((select %1$I.is_master()) or city_id = (select %1$I.user_city()))', s);
  execute format('create policy "master or own state" on %1$I.kv_store for all to authenticated '
                 'using ((select %1$I.is_master()) or city_id = (select %1$I.user_city())) '
                 'with check ((select %1$I.is_master()) or city_id = (select %1$I.user_city()))', s);
  -- A per-state key must name the same state as its city_id, so a state login
  -- can't plant "components@<another state>".
  execute format('drop policy if exists "per-state keys match state" on %I.kv_store', s);
  execute format('create policy "per-state keys match state" on %I.kv_store as restrictive for all to authenticated '
                 'using (true) '
                 'with check (position(''@'' in key) = 0 or key = split_part(key, ''@'', 1) || ''@'' || city_id)', s);
  execute format('revoke all on %I.works, %I.gantt_data, %I.budget_matrix, %I.kv_store from anon', s, s, s, s);
  execute format('grant select, insert, update, delete on %I.works, %I.gantt_data, %I.budget_matrix, %I.kv_store to authenticated', s, s, s, s);
  execute format('grant all on all tables in schema %I to service_role', s);
  execute format('grant usage, select on all sequences in schema %I to authenticated, service_role', s);
end
$setup$;
revoke all on function public.mitigation_setup_schema(text) from public, anon, authenticated;

